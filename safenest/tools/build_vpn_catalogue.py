#!/usr/bin/env python3
"""Build assets/blocked_apps/vpn_apps.txt from public sources listed in data/vpn-app-sources.json.

    curl -sSL -o /tmp/fdroid/index-v2.json https://f-droid.org/repo/index-v2.json
    python -I tools/build_vpn_catalogue.py /tmp/fdroid/index-v2.json

Standard library only. Output is sorted, so a rerun with the same index gives the same file.
Entries: "package | Name" (both block), or "| Name" (store-title block only). Update the
"fetched" date in the sources file when you refresh the index.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "data" / "vpn-app-sources.json"
OUT = ROOT / "android" / "app" / "src" / "main" / "assets" / "blocked_apps" / "vpn_apps.txt"
PACKAGE = re.compile(r"^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$", re.I)
# F-Droid names carry taglines ("Proton VPN - Secure and Free VPN"); the store-title match wants the brand.
SEPARATORS = re.compile(r"\s+[-–—:|(]\s*|\s*[:(]")


def text(value) -> str:
    if isinstance(value, dict):
        return value.get("en-US") or next(iter(value.values()), "")
    return value or ""


def brand(name: str) -> str:
    short = SEPARATORS.split(name.strip(), maxsplit=1)[0].strip()
    return short if len(short) >= 3 else name.strip()


def main(index_path: str) -> int:
    sources = json.loads(SOURCES.read_text(encoding="utf-8"))
    rows: dict[str, str] = {}  # package -> name; "" package keys by name

    fd = sources["fdroid"]
    index = json.loads(Path(index_path).read_text(encoding="utf-8"))
    for pkg, app in index["packages"].items():
        meta = app.get("metadata", {})
        in_category = fd["category"] in meta.get("categories", [])
        if (in_category and pkg not in fd["exclude"]) or pkg in fd["include_outside_category"]:
            if not PACKAGE.match(pkg):
                raise SystemExit(f"unexpected package id in index: {pkg}")
            name = brand(text(meta.get("name")))
            # Ambiguous names block by package only; the store title then has to say "VPN" or "proxy".
            rows[pkg] = "" if name in fd["package_only_names"] else name

    known = json.loads((ROOT / sources["known_packages_file"]).read_text(encoding="utf-8"))
    for app in known["apps"]:
        rows[app["package_name"]] = app["name"]

    names = {row for row in rows.values()}
    for entry in sources["names"]:
        if entry["name"] not in names:
            rows[f"|{entry['name']}"] = entry["name"]

    lines = [
        "# SafeNest — VPN and proxy apps. Generated by tools/build_vpn_catalogue.py; edit data/vpn-app-sources.json instead.",
        "# Opening a listed app returns Home during protection, and so does its install page (matched by the name",
        f"# shown on the store). Sources: F-Droid index ({fd['index_url']}, fetched {fd['fetched']},",
        "# category \"VPN & Proxy\"), data/known-vpn-packages.json, and the Wikipedia lists cited in the sources file.",
        "# Format: package ID | name, or | name for a store-title entry without a known package ID.",
    ]
    packaged = sorted((p, n) for p, n in rows.items() if not p.startswith("|"))
    name_only = sorted(n for p, n in rows.items() if p.startswith("|"))
    lines += [f"{p} | {n}".rstrip() for p, n in packaged]
    lines += [f"| {n}" for n in name_only]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {len(packaged)} packages, {len(name_only)} name-only entries")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    raise SystemExit(main(sys.argv[1]))
