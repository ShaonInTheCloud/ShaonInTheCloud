// Compiles the gambling list for the DNS filter (iPhone profile) from the same sources as the
// Android app's bundled blocklist (data/blocklists, 541,485 names) plus data/safenest-gambling-domains.txt.
// Output: gzip+base64 of the sorted list, decoded at boot into a SortedDomainList.
//   node scripts/build-dns-domains.mjs
import {readFileSync, readdirSync, writeFileSync} from 'node:fs';
import {gzipSync} from 'node:zlib';

const root = new URL('../data/', import.meta.url);
const read = rel => readFileSync(new URL(rel, root), 'utf8');
const hostPattern = /^(?=.{4,253}$)(?!-)[a-z0-9-]{1,63}(\.[a-z0-9-]{1,63})+$/;

export function normalize(raw) {
  let v = String(raw).trim().toLowerCase();
  if (!v || v.startsWith('#')) return null;
  v = v.replace(/^(0\.0\.0\.0|127\.0\.0\.1)\s+/, '').split(/\s+/)[0].replace(/^\*\./, '').replace(/^\|\|/, '').replace(/\^$/, '').replace(/\.$/, '');
  return hostPattern.test(v) && !/^\d+(\.\d+)+$/.test(v) ? v : null;
}

export function compile() {
  const exclusions = new Set(read('blocklists/exclusions.txt').split(/\r?\n/).map(normalize).filter(Boolean));
  const files = [
    ...readdirSync(new URL('blocklists/sources/', root)).map(f => `blocklists/sources/${f}`),
    ...readdirSync(new URL('blocklists/gpl3/', root)).filter(f => /\.(txt|tsv)$/.test(f)).map(f => `blocklists/gpl3/${f}`),
    'safenest-gambling-domains.txt',
  ].filter(f => /\.(txt|tsv)$/.test(f));
  const all = new Set(), report = [];
  for (const file of files) {
    let accepted = 0, excluded = 0;
    for (const line of read(file).split(/\r?\n/)) {
      const host = normalize(line.includes('\t') ? line.split('\t')[0] : line.replace(/^(0\.0\.0\.0|127\.0\.0\.1)\s+/, ''));
      if (!host) continue;
      if (exclusions.has(host)) { excluded++; continue; }
      all.add(host); accepted++;
    }
    report.push({file, accepted, excluded});
  }
  return {list: [...all].sort(), report, exclusions: exclusions.size};
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const {list, report} = compile();
  const payload = gzipSync(Buffer.from(list.join('\n') + '\n'), {level: 9}).toString('base64');
  writeFileSync(new URL('../supabase/functions/dns-query/domains.generated.mjs', import.meta.url),
    `// Generated by scripts/build-dns-domains.mjs — do not edit. Sources: data/blocklists (incl. HaGeZi, GPL-3.0,\n` +
    `// see data/blocklists/licenses) and data/safenest-gambling-domains.txt. gzip+base64 of the sorted list.\n` +
    `export const BUNDLED_COUNT = ${list.length};\nexport const BUNDLED_GZIP_BASE64 = ${JSON.stringify(payload)};\n`);
  for (const r of report) console.log(`${String(r.accepted).padStart(7)} accepted ${String(r.excluded).padStart(3)} excluded  ${r.file}`);
  console.log(`dns-query: bundled ${list.length} unique domains (${(payload.length / 1e6).toFixed(1)} MB payload)`);
}
