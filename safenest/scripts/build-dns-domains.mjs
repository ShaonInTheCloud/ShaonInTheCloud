// Regenerates the gambling list bundled into the DNS filter from data/safenest-gambling-domains.txt.
// Run after the data file changes: node scripts/build-dns-domains.mjs
import {readFileSync, writeFileSync} from 'node:fs';
import {parseDomainList} from '../supabase/functions/_shared/doh.mjs';
const src = new URL('../data/safenest-gambling-domains.txt', import.meta.url);
const out = new URL('../supabase/functions/dns-query/domains.generated.mjs', import.meta.url);
const list = [...parseDomainList(readFileSync(src, 'utf8'))].sort();
writeFileSync(out, `// Generated by scripts/build-dns-domains.mjs from data/safenest-gambling-domains.txt — do not edit.\nexport const BUNDLED_COUNT = ${list.length};\nexport const BUNDLED_DOMAINS = ${JSON.stringify(list.join('\n'))};\n`);
console.log(`dns-query: bundled ${list.length} domains`);
