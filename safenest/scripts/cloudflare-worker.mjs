// The current static host ignores dist/_headers, but mysafenestbd.com is served through Cloudflare.
// This turns the same header policy into a Cloudflare Worker so HSTS, CSP frame-ancestors,
// no-store and no-referrer are actually enforced on live responses.
export function parseHeaders(text) {
  const rules = [];
  let current = null;
  for (const line of text.split('\n')) {
    if (!line.trim()) continue;
    if (!/^\s/.test(line)) { current = { path: line.trim(), headers: {} }; rules.push(current); continue; }
    const at = line.indexOf(':');
    if (!current || at < 1) throw new Error('Malformed headers file');
    current.headers[line.slice(0, at).trim()] = line.slice(at + 1).trim();
  }
  return rules;
}
export function workerSource(headersText) {
  const rules = parseHeaders(headersText);
  return `// Generated by scripts/cloudflare-worker.mjs. Do not edit; rebuild instead.
const RULES = ${JSON.stringify(rules)};
export default {
  async fetch(request) {
    const response = await fetch(request);
    const path = new URL(request.url).pathname;
    const headers = new Headers(response.headers);
    for (const rule of RULES) {
      if (rule.path === '/*' || rule.path === path) for (const [k, v] of Object.entries(rule.headers)) headers.set(k, v);
    }
    return new Response(response.body, { status: response.status, statusText: response.statusText, headers });
  }
};
`;
}
